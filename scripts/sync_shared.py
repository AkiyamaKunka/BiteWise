#!/usr/bin/env python3
"""Generate the Python and Dart bindings from shared/ sources.

shared/prompts/*.txt, shared/prompts/restaurant_lookup_schema.json,
shared/chains/us_chains.json and shared/constants.json are the single source
of truth for everything the server (Python) and the mobile app (Dart) must
agree on. This script emits:

  shared_generated.py               (imported by config.py / telegram_bot.py)
  app/lib/core/shared_generated.dart (imported by the app's core/prompts + modules)

Run with --check to verify the generated files are up to date (used by both
test suites as a drift gate): exit 1 means someone edited a generated file
or the shared source without regenerating.

Encoding rules:
  - The text-handler template in shared/ uses <<TOKEN>> placeholders and
    SINGLE braces for literal JSON. The Python binding re-encodes it for
    str.format (braces doubled, tokens -> {placeholders}); the Dart binding
    keeps <<TOKEN>> and substitutes via replaceAll at runtime (no Dart
    string-interpolation escaping hazards).
  - The restaurant-lookup prompt keeps its single <<REQUEST_JSON>> token on
    both sides; restaurant_lookup.py and core/restaurant_lookup_contract.dart
    substitute the composed request. The response schema is emitted as its
    compact JSON text (the exact string a --json-schema flag or an API
    request carries), and the US chain table as data (a list of dicts in
    Python, a const list of SharedChain in Dart).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared"
PY_OUT = ROOT / "shared_generated.py"
DART_OUT = ROOT / "app" / "lib" / "core" / "shared_generated.dart"

HEADER = "AUTO-GENERATED by scripts/sync_shared.py from shared/ — DO NOT EDIT. Edit shared/prompts/*, shared/chains/us_chains.json or shared/constants.json and regenerate."

TOKENS = ["TODAY", "WEEKDAY", "YESTERDAY", "MEALS_LIST", "USER_MESSAGE"]


def load_sources():
    food = (SHARED / "prompts" / "food_detection_prompt.txt").read_text(encoding="utf-8")
    text = (SHARED / "prompts" / "text_handler_prompt.txt").read_text(encoding="utf-8")
    constants = json.loads((SHARED / "constants.json").read_text(encoding="utf-8"))
    constants.pop("_comment", None)

    # The estimation-priority "skill" file: an editable evidence ladder
    # (nutrition label > printed weight > brand data > visual estimate)
    # spliced into the photo prompt AT GENERATION TIME, so adding a
    # priority never touches either platform's code. '#' lines are the
    # file's own documentation, not prompt text.
    priority_raw = (SHARED / "prompts" / "estimation_priority.txt").read_text(
        encoding="utf-8"
    )
    priority = "\n".join(
        ln for ln in priority_raw.splitlines() if not ln.startswith("#")
    ).strip()
    if not priority:
        raise SystemExit("estimation_priority.txt has no prompt content")
    if "<<ESTIMATION_PRIORITY>>" not in food:
        raise SystemExit(
            "food_detection_prompt.txt lost its <<ESTIMATION_PRIORITY>> "
            "placeholder — the priority ladder would silently vanish"
        )
    food = food.replace("<<ESTIMATION_PRIORITY>>", priority)
    if "<<ESTIMATION_PRIORITY>>" in food or "Priority 1" not in food:
        raise SystemExit("estimation-priority splice failed")

    leftover = (SHARED / "prompts" / "leftover_prompt.txt").read_text(
        encoding="utf-8"
    )
    if "<<ORIGINAL_ANALYSIS>>" not in leftover:
        raise SystemExit("leftover_prompt.txt lost <<ORIGINAL_ANALYSIS>>")
    return food, text, leftover, constants


def load_lookup_sources():
    """The restaurant-lookup prompt, its response schema and the US chain
    table, each checked for the shape both composers rely on."""
    prompt = (SHARED / "prompts" / "restaurant_lookup_prompt.txt").read_text(
        encoding="utf-8"
    )
    # The composed request is spliced in at exactly one place, inside the
    # only <data> block, at the very end of the prompt.
    if prompt.count("<<REQUEST_JSON>>") != 1:
        raise SystemExit(
            "restaurant_lookup_prompt.txt needs exactly one <<REQUEST_JSON>>")
    if prompt.count("<data>") != 1 or prompt.count("</data>") != 1:
        raise SystemExit(
            "restaurant_lookup_prompt.txt needs exactly one <data> block")
    if not prompt.endswith("<data>\n<<REQUEST_JSON>>\n</data>\n"):
        raise SystemExit(
            "restaurant_lookup_prompt.txt must end with the <data> block")

    schema = json.loads(
        (SHARED / "prompts" / "restaurant_lookup_schema.json").read_text(
            encoding="utf-8"))
    if schema.get("type") != "object" or "properties" not in schema:
        raise SystemExit("restaurant_lookup_schema.json is not an object schema")
    schema_text = json.dumps(schema, ensure_ascii=False, separators=(",", ":"))

    table = json.loads(
        (SHARED / "chains" / "us_chains.json").read_text(encoding="utf-8"))
    chains = table.get("chains")
    if not isinstance(chains, list) or not chains:
        raise SystemExit("us_chains.json has no chains")
    fields = ("key", "name", "zh_name", "aliases", "domains", "size")
    out = []
    for c in chains:
        extra = set(c) - set(fields)
        if extra:
            raise SystemExit("us_chains.json: unknown field(s) %s in %r"
                             % (sorted(extra), c.get("key")))
        entry = {"key": c["key"], "name": c["name"]}
        if c.get("zh_name"):
            entry["zh_name"] = c["zh_name"]
        entry["aliases"] = list(c.get("aliases", []))
        entry["domains"] = list(c["domains"])
        entry["size"] = c["size"]
        out.append(entry)
    return prompt, schema_text, str(table["as_of"]), out


def python_binding(food, text, leftover, constants, lookup):
    fmt = text.replace("{", "{{").replace("}", "}}")
    for token in TOKENS:
        fmt = fmt.replace("<<%s>>" % token, "{%s}" % token.lower())
    left_fmt = leftover.replace("{", "{{").replace("}", "}}").replace(
        "<<ORIGINAL_ANALYSIS>>", "{original_analysis}"
    )
    lines = ['"""%s"""' % HEADER, ""]
    lines.append("FOOD_DETECTION_PROMPT_RAW = %r" % food)
    lines.append("")
    lines.append("TEXT_HANDLER_PROMPT_TEMPLATE = %r" % fmt)
    lines.append("")
    lines.append("LEFTOVER_PROMPT_TEMPLATE = %r" % left_fmt)
    lines.append("")
    for key, value in constants.items():
        lines.append("%s = %r" % (key.upper(), value))
    lines.append("")
    lines.append("CONSTANTS = %r" % (constants,))
    lines.append("")
    prompt, schema_text, as_of, chains = lookup
    lines.append("# Restaurant lookup (shared/prompts/restaurant_lookup_*). The prompt")
    lines.append("# keeps its <<REQUEST_JSON>> token: compose with restaurant_lookup.py.")
    lines.append("RESTAURANT_LOOKUP_PROMPT = %r" % prompt)
    lines.append("")
    lines.append("RESTAURANT_LOOKUP_SCHEMA = %r" % schema_text)
    lines.append("")
    lines.append("# shared/chains/us_chains.json")
    lines.append("US_CHAINS_AS_OF = %r" % as_of)
    lines.append("")
    lines.append("US_CHAINS = [")
    for c in chains:
        lines.append("    %r," % (c,))
    lines.append("]")
    lines.append("")
    return "\n".join(lines)


def _dart_quote(s):
    """A single-quoted Dart string literal with no interpolation."""
    return "'%s'" % (
        s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
        .replace("\n", "\\n"))


def _dart_lookup_lines(lookup, dart_str):
    prompt, schema_text, as_of, chains = lookup
    lines = []
    lines.append("/// The restaurant-lookup prompt TEMPLATE: compose it with")
    lines.append("/// core/restaurant_lookup_contract.dart, which splices the composed")
    lines.append("/// request in place of `<<REQUEST_JSON>>`.")
    lines.append("const String sharedRestaurantLookupPrompt = %s;" % dart_str(prompt))
    lines.append("")
    lines.append("/// The lookup response schema as compact JSON text.")
    lines.append("const String sharedRestaurantLookupSchema = %s;"
                 % _dart_quote(schema_text))
    lines.append("")
    lines.append("/// One row of shared/chains/us_chains.json.")
    lines.append("final class SharedChain {")
    lines.append("  const SharedChain({")
    lines.append("    required this.key,")
    lines.append("    required this.name,")
    lines.append("    this.zhName,")
    lines.append("    required this.aliases,")
    lines.append("    required this.domains,")
    lines.append("    required this.size,")
    lines.append("  });")
    lines.append("")
    lines.append("  final String key;")
    lines.append("  final String name;")
    lines.append("  final String? zhName;")
    lines.append("  final List<String> aliases;")
    lines.append("  final List<String> domains;")
    lines.append("  final String size;")
    lines.append("}")
    lines.append("")
    lines.append("const String sharedUsChainsAsOf = %s;" % _dart_quote(as_of))
    lines.append("")
    lines.append("const List<SharedChain> sharedUsChains = [")
    for c in chains:
        parts = ["key: %s" % _dart_quote(c["key"]),
                 "name: %s" % _dart_quote(c["name"])]
        if c.get("zh_name"):
            parts.append("zhName: %s" % _dart_quote(c["zh_name"]))
        parts.append("aliases: [%s]" % ", ".join(_dart_quote(a) for a in c["aliases"]))
        parts.append("domains: [%s]" % ", ".join(_dart_quote(d) for d in c["domains"]))
        parts.append("size: %s" % _dart_quote(c["size"]))
        lines.append("  SharedChain(%s)," % ", ".join(parts))
    lines.append("];")
    lines.append("")
    return lines


def dart_binding(food, text, leftover, constants, lookup):
    def dart_str(s):
        return "'''\n%s'''" % s.replace("\\", "\\\\").replace("$", "\\$").replace("'''", "\\'\\'\\'")

    def dart_val(v):
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, float):
            return repr(v)
        if isinstance(v, int):
            return str(v)
        return "'%s'" % str(v).replace("\\", "\\\\").replace("'", "\\'")

    def camel(k):
        parts = k.split("_")
        return parts[0] + "".join(p.capitalize() for p in parts[1:])

    lines = ["// %s" % HEADER, "", "library;", ""]
    lines.append("const String sharedFoodDetectionPrompt = %s;" % dart_str(food))
    lines.append("")
    lines.append("const String sharedTextHandlerTemplate = %s;" % dart_str(text))
    lines.append("")
    lines.append("const String sharedLeftoverTemplate = %s;" % dart_str(leftover))
    lines.append("")
    lines.append("/// The leftover-deduction prompt with the original analysis spliced in.")
    lines.append("String sharedLeftoverPrompt({required String originalAnalysis}) =>")
    lines.append("    sharedLeftoverTemplate.replaceAll(")
    lines.append("        '<<ORIGINAL_ANALYSIS>>', originalAnalysis);")
    lines.append("")
    lines.append("/// Substitutes the `<<TOKEN>>` placeholders. Kept as replaceAll so the")
    lines.append("/// template needs no Dart interpolation escaping.")
    lines.append("String sharedTextHandlerPrompt({")
    lines.append("  required String mealsList,")
    lines.append("  required String userMessage,")
    lines.append("  required String today,")
    lines.append("  required String weekday,")
    lines.append("  required String yesterday,")
    lines.append("}) => sharedTextHandlerTemplate")
    lines.append("    .replaceAll('<<TODAY>>', today)")
    lines.append("    .replaceAll('<<WEEKDAY>>', weekday)")
    lines.append("    .replaceAll('<<YESTERDAY>>', yesterday)")
    lines.append("    .replaceAll('<<MEALS_LIST>>', mealsList)")
    lines.append("    .replaceAll('<<USER_MESSAGE>>', userMessage);")
    lines.append("")
    lines.append("abstract final class SharedConstants {")
    for key, value in constants.items():
        typ = "bool" if isinstance(value, bool) else (
            "double" if isinstance(value, float) else (
                "int" if isinstance(value, int) else "String"))
        lines.append("  static const %s %s = %s;" % (typ, camel(key), dart_val(value)))
    lines.append("}")
    lines.append("")
    lines.extend(_dart_lookup_lines(lookup, dart_str))
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    food, text, leftover, constants = load_sources()
    lookup = load_lookup_sources()
    outputs = {PY_OUT: python_binding(food, text, leftover, constants, lookup),
               DART_OUT: dart_binding(food, text, leftover, constants, lookup)}
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            if check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(content, encoding="utf-8")
                print("wrote %s" % path.relative_to(ROOT))
    if check:
        if stale:
            print("STALE generated bindings (run scripts/sync_shared.py): %s" % ", ".join(stale))
            return 1
        print("shared bindings in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
